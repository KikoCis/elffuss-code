// Monaco 0.52.2's built-in languages, as Code's page sees them before any
// extension: their ids, and whether each is a Monarch language (its definition
// has a `loader`, so an extension's TextMate grammar can replace its colouring;
// the others, such as JSON, keep their own). The panel asks the live editor
// (js/ext/host.js: builtinLanguage, grammarSkippedFor); the static catalog
// census, which runs in Node, reads the same list from monaco-languages.json.
//
//   node tests/lib/monaco-languages.mjs          print the live list
//   node tests/lib/monaco-languages.mjs --write  rewrite monaco-languages.json
// tests/x2_ux.mjs checks that the file still matches the live editor.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const FILE = path.join(HERE, 'monaco-languages.json');

// in a page of Code where Monaco is loaded
export const liveLanguages = page => page.evaluate(() => window.monaco.languages.getLanguages()
  .map(l => ({ id: l.id, monarch: typeof l.loader === 'function' }))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0)));

export const readLanguages = () => JSON.parse(fs.readFileSync(FILE, 'utf8'));

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { chromium } = await import('playwright');
  const { startServer } = await import('./x2-server.mjs');
  const srv = await startServer();
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.goto(srv.codeOrigin + '/?test-opfs&noext', { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => !!window.monaco?.languages?.getLanguages?.().length, null, { timeout: 60000 });
    const languages = await liveLanguages(page);
    const out = { monaco: '0.52.2', note: 'Generated by tests/lib/monaco-languages.mjs --write from the live editor; tests/x2_ux.mjs checks it.', languages };
    if (process.argv.includes('--write')) { fs.writeFileSync(FILE, JSON.stringify(out, null, 1) + '\n'); console.log(`${languages.length} languages written`); }
    else console.log(JSON.stringify(out, null, 1));
  } finally { await browser.close(); await srv.close(); }
}
